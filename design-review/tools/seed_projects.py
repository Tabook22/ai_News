def main():
    with m.app.app_context():
        created = updated = 0
        for data in IDEAS:
            row = m.ProjectIdea.query.filter_by(title_en=data["title_en"]).first()
            if row is None:
                row = m.ProjectIdea(title_en=data["title_en"])
                m.db.session.add(row)
                created += 1
            else:
                updated += 1
            for key, value in data.items():
                setattr(row, key, value)
            row.is_published = True
            row.track = data.get('track', 'final_year')
        m.db.session.commit()
        print(f"Project ideas: {created} created, {updated} updated, total {m.ProjectIdea.query.count()}")


