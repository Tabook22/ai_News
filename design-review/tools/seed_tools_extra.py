def main():
    with m.app.app_context():
        created = updated = 0
        for data in TOOLS:
            tool = m.AITool.query.filter_by(name=data["name"]).first()
            if tool is None:
                tool = m.AITool(name=data["name"])
                m.db.session.add(tool)
                created += 1
            else:
                updated += 1
            for key, value in data.items():
                setattr(tool, key, value)
            tool.is_published = True
            tool.last_checked = CHECKED
            tool.related_article_ids = tool.related_article_ids or "[]"

        gamma = m.AITool.query.filter_by(name="Gamma").first()
        if gamma:
            gamma.category = "presentations"

        m.db.session.commit()
        print(f"Extra AI tools: {created} created, {updated} updated, total {m.AITool.query.count()}")


